def main() -> None:
    cases = []
    for category, texts in VIOLATIONS.items():
        cases += [{"text": t, "expect": "violation", "category": category} for t in texts]
    cases += [{"text": t, "expect": "clean", "category": "clean"} for t in CLEAN]
    texts = [c["text"] for c in cases]
    assert len(texts) == len(set(texts)), "duplicate case"
    assert len(cases) >= 300, len(cases)
    path = Path(__file__).parent / "compliance_cases.jsonl"
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for i, c in enumerate(cases, 1):
            f.write(json.dumps({"id": i, **c}, ensure_ascii=False) + "\n")
    print(f"wrote {len(cases)} cases to {path}")


if __name__ == "__main__":
    main()
